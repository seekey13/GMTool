--[[
    Writes docs/commands.md from the catalog: every command GM Tool has a form for, by page, with its GM level,
    arguments and what it does. Run from the repo root after changing core/catalog.lua or data/server.lua:

        luajit tools/gen_docs.lua
]]--

package.path = './?.lua;' .. package.path
local catalog = require('core.catalog')
local server = require('data.server')

local KIND = { int = 'number', num = 'number', word = 'word', text = 'text', player = 'player', pick = 'pick',
               choice = 'choice', entity = 'mob/NPC id', item = 'item', spell = 'spell' }

local function arg_text(a)
    local s = a[1]
    if a[2] == 'pick' then s = s .. ' (' .. a.set .. ')' elseif a[2] ~= 'player' then s = s .. ' (' .. KIND[a[2]] .. ')' end
    return a.req and ('<' .. s .. '>') or ('[' .. s .. ']')
end

local out = { '# GM commands', '',
    ('Generated by `tools/gen_docs.lua` from `core/catalog.lua`: %d forms for the %d commands in the server\'s '
        .. '`scripts/commands/`. `<...>` must be given, `[...]` may be left empty. GM levels are the server\'s own '
        .. '(`cmdprops.permission`).'):format(#catalog.list, (function () local n = 0 for _ in pairs(server) do n = n + 1 end return n end)()),
    '' }

for _, p in ipairs(catalog.PAGES) do
    local page = catalog.page_of[p[1]]
    out[#out + 1] = '## ' .. page.title
    out[#out + 1] = ''
    out[#out + 1] = page.blurb
    out[#out + 1] = ''
    out[#out + 1] = '| Command | GM | Arguments | What it does |'
    out[#out + 1] = '|---|---|---|---|'
    for _, c in ipairs(page.commands) do
        local args = {}
        for _, a in ipairs(c.args) do args[#args + 1] = arg_text(a) end
        local title = c.title ~= '!' .. c.cmd and ('`!%s` (%s)'):format(c.cmd, c.title) or ('`!%s`'):format(c.cmd)
        local desc = (c.desc or ''):gsub('|', '\\|')
        if c.note then desc = desc .. ' ' .. c.note:gsub('|', '\\|') end
        if c.danger then desc = '**Asks twice.** ' .. desc end
        out[#out + 1] = ('| %s | %d | %s | %s |'):format(title, server[c.cmd].level, table.concat(args, ' '):gsub('|', '\\|'), desc)
    end
    out[#out + 1] = ''
end

local f = assert(io.open('docs/commands.md', 'wb'))
f:write(table.concat(out, '\n'))
f:close()
print('wrote docs/commands.md')
