--[[
    Regenerates data/*.lua from the CatsEyeXI server source (a LandSandBoat fork). Run from the repo root:

        luajit tools/gen_data.lua [path to the server checkout]

    The path defaults to ../../../../../catseyexi, where the dev setup keeps the server beside the client. Nothing in
    the addon runs this: data/ is committed, so a GM without the server source still has every list.

    It reads, and never runs anything but the enum and quest/mission tables (in a sandbox with no io or os):
      scripts/commands/*.lua      -> data/server.lua     each command's GM level, parameters, usage and description
      scripts/enum/*.lua          -> data/<enum>.lua     effects, mods, zones, skills, key items, titles ...
      scripts/globals/quests.lua  -> data/quests.lua     quest ids per quest log
      scripts/globals/missions.lua-> data/missions.lua   mission ids per mission log
      sql/char_points.sql         -> data/currencies.lua the currency names !addcurrency takes
]]--

local root = (arg and arg[1]) or '../../../../../catseyexi'
root = root:gsub('[/\\]+$', '')

local function read(path)
    local f = io.open(path, 'rb')
    if not f then return nil end
    local s = f:read('*a')
    f:close()
    return s
end

local function must(path)
    local s = read(path)
    if not s then error('cannot read ' .. path .. ' (pass the server checkout as the first argument)', 0) end
    return s
end

local function list_dir(dir)
    local windows = package.config:sub(1, 1) == '\\'
    local cmd = windows and ('dir /b "' .. dir:gsub('/', '\\') .. '"') or ('ls "' .. dir .. '"')
    local out = {}
    local p = io.popen(cmd)
    for line in p:lines() do out[#out + 1] = line end
    p:close()
    table.sort(out)
    return out
end

-- A Lua string literal for `s`, ASCII only (anything else escaped).
local function lit(s)
    return '\'' .. tostring(s):gsub('[\\\']', '\\%0'):gsub('\r', ''):gsub('\n', '\\n'):gsub('[^\32-\126]', function (c)
        return ('\\%d'):format(c:byte())
    end) .. '\''
end

local function write(name, header, body)
    local path = 'data/' .. name .. '.lua'
    local f = assert(io.open(path, 'wb'))
    f:write('-- ', header, '\n-- Generated by tools/gen_data.lua from the CatsEyeXI server source: do not edit by hand.\n')
    f:write(body)
    f:close()
    print(('wrote %s (%d bytes)'):format(path, #body))
end

-- Runs `src` with `env` as its globals (no io, os, require), returning env.
local function sandbox(src, chunkname, env)
    local fn, err = loadstring(src, '=' .. chunkname)
    if not fn then error(err, 0) end
    setfenv(fn, env)
    local ok, e = pcall(fn)
    if not ok then error(chunkname .. ': ' .. tostring(e), 0) end
    return env
end

local function base_env()
    return { xi = {}, pairs = pairs, ipairs = ipairs, type = type, tostring = tostring, tonumber = tonumber,
             string = string, table = table, math = math, setmetatable = setmetatable, bit = bit, print = function () end }
end

-- { { id, NAME }, ... } sorted by id then name, from an enum table; numbers only.
local function pairs_of(t)
    local out = {}
    for k, v in pairs(t) do
        if type(k) == 'string' and type(v) == 'number' then out[#out + 1] = { v, k } end
    end
    table.sort(out, function (a, b) if a[1] ~= b[1] then return a[1] < b[1] end return a[2] < b[2] end)
    return out
end

local function list_body(entries)
    local lines = { 'return {' }
    for _, e in ipairs(entries) do lines[#lines + 1] = ('{%d,%s},'):format(e[1], lit(e[2])) end
    lines[#lines + 1] = '}\n'
    return table.concat(lines, '\n')
end

-- Commands ---------------------------------------------------------------------------------------------------------

local function command_info(src)
    local info = { level = tonumber(src:match('permission%s*=%s*(%d+)')), params = src:match('parameters%s*=%s*\'([^\']*)\'') }
    info.desc = src:match('%-%-%s*desc:%s*([^\r\n]*)')
    info.func = src:match('%-%-%s*func:%s*([^\r\n]*)')
    local usage = {}
    for u in src:gmatch('printToPlayer%(%s*[\'"](![^\'"]*)[\'"]') do usage[#usage + 1] = u end
    info.usage = usage[1]
    if info.desc then info.desc = info.desc:gsub('%s+$', '') end
    if info.desc == '' then info.desc = nil end
    return info
end

local cmds = {}
for _, f in ipairs(list_dir(root .. '/scripts/commands')) do
    local name = f:match('^(.+)%.lua$')
    if name then cmds[#cmds + 1] = { name = name, info = command_info(must(root .. '/scripts/commands/' .. f)) } end
end
do
    local lines = { 'return {' }
    for _, c in ipairs(cmds) do
        local i = c.info
        lines[#lines + 1] = ('[%s]={level=%d,params=%s%s%s},'):format(lit(c.name), i.level or 0, lit(i.params or ''),
            i.usage and (',usage=' .. lit(i.usage)) or '', i.desc and (',desc=' .. lit(i.desc)) or '')
    end
    lines[#lines + 1] = '}\n'
    write('server', ('%d GM commands: each one\'s GM level, parameter types and usage, from scripts/commands'):format(#cmds),
        table.concat(lines, '\n'))
end

-- Enums ------------------------------------------------------------------------------------------------------------

local ENUMS = {
    -- file, field of xi, output name, what it is
    { 'effect', 'effect', 'effects', 'Status effects (xi.effect)' },
    { 'mod', 'mod', 'mods', 'Modifiers (xi.mod)' },
    { 'mob_mod', 'mobMod', 'mobmods', 'Mob modifiers (xi.mobMod)' },
    { 'zone', 'zone', 'zones', 'Zones (xi.zone)' },
    { 'skill', 'skill', 'skills', 'Skills (xi.skill)' },
    { 'weather', 'weather', 'weather', 'Weather (xi.weather)' },
    { 'key_item', 'keyItem', 'keyitems', 'Key items (xi.keyItem)' },
    { 'title', 'title', 'titles', 'Titles (xi.title)' },
    { 'mount', 'mount', 'mounts', 'Mounts (xi.mount)' },
    { 'nation', 'nation', 'nations', 'Nations (xi.nation)' },
    { 'allegiance', 'allegiance', 'allegiances', 'Allegiances (xi.allegiance)' },
    { 'animation', 'animation', 'animations', 'Animations (xi.animation)' },
    { 'job', 'job', 'jobs', 'Jobs (xi.job)' },
    { 'slot', 'slot', 'slots', 'Equipment slots (xi.slot)' },
    { 'inventory_location', 'inventoryLocation', 'containers', 'Containers (xi.inventoryLocation)' },
    { 'fame_area', 'fameArea', 'fame', 'Fame areas (xi.fameArea)' },
    { 'craft_rank', 'craftRank', 'craftranks', 'Craft ranks (xi.craftRank)' },
}

for _, e in ipairs(ENUMS) do
    local src = must(root .. '/scripts/enum/' .. e[1] .. '.lua')
    local env = sandbox(src, e[1] .. '.lua', base_env())
    local t = env.xi[e[2]]
    if type(t) ~= 'table' then error(('scripts/enum/%s.lua has no xi.%s'):format(e[1], e[2]), 0) end
    local entries = pairs_of(t)
    if e[3] == 'zones' then  -- MAX_ZONE is a bound, not a zone
        local kept = {}
        for _, z in ipairs(entries) do if z[2] ~= 'MAX_ZONE' then kept[#kept + 1] = z end end
        entries = kept
    end
    write(e[3], ('%s: %d entries, { id, NAME }'):format(e[4], #entries), list_body(entries))
end

-- Quests and missions ----------------------------------------------------------------------------------------------

-- { { log = id, name = AREA_KEY, entries = { { id, NAME } } }, ... } by log id.
local function logs_body(logs)
    local lines = { 'return {' }
    for _, l in ipairs(logs) do
        lines[#lines + 1] = ('{log=%d,name=%s,entries={'):format(l.log, lit(l.name))
        for _, q in ipairs(l.entries) do lines[#lines + 1] = ('{%d,%s},'):format(q[1], lit(q[2])) end
        lines[#lines + 1] = '}},'
    end
    lines[#lines + 1] = '}\n'
    return table.concat(lines, '\n')
end

do
    local env = base_env()
    sandbox(must(root .. '/scripts/enum/quest_log.lua'), 'quest_log.lua', env)
    sandbox(must(root .. '/scripts/globals/quests.lua'), 'quests.lua', env)
    local logs = {}
    for name, id in pairs(env.xi.questLog) do
        local area = env.xi.quest.area[id]
        local ids = area and env.xi.quest.id[area]
        if ids then logs[#logs + 1] = { log = id, name = name, entries = pairs_of(ids) } end
    end
    table.sort(logs, function (a, b) return a.log < b.log end)
    write('quests', 'Quest ids per quest log (xi.quest.id)', logs_body(logs))
end

do
    local env = base_env()
    sandbox(must(root .. '/scripts/globals/missions.lua'), 'missions.lua', env)
    local logs = {}
    for name, id in pairs(env.xi.mission.log_id) do
        local area = env.xi.mission.area[id]
        local ids = area and env.xi.mission.id[area]
        if ids then logs[#logs + 1] = { log = id, name = name, entries = pairs_of(ids) } end
    end
    table.sort(logs, function (a, b) return a.log < b.log end)
    write('missions', 'Mission ids per mission log (xi.mission.id)', logs_body(logs))
end

-- Currencies -------------------------------------------------------------------------------------------------------

do
    local sql = must(root .. '/sql/char_points.sql')
    local names = {}
    for col in sql:gmatch('\n%s*`([%w_]+)`') do
        if col ~= 'charid' then names[#names + 1] = col end
    end
    local lines = { 'return {' }
    for _, n in ipairs(names) do lines[#lines + 1] = lit(n) .. ',' end
    lines[#lines + 1] = '}\n'
    write('currencies', ('%d currency names !addcurrency and !delcurrency take (char_points columns)'):format(#names),
        table.concat(lines, '\n'))
end
