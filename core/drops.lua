--[[
    Mobs' drop lists, from the server's sql/mob_droplist.sql (data/drops.lua, generated by tools/gen_data.lua). A
    mob group names its list (core/spawns.lua's `drop`). Pure; each list parsed the first time it's wanted.

    A drop is { kind = 'drop' | 'group' | 'steal' | 'despoil', group, group_rate, item (its id), rate, rolls, share,
    chance }, rates per 1000 as the server keeps them (src/map/entities/mobentity.cpp, DropItems):
      - a 'drop' rolls on its own at its rate; the same item listed twice rolls twice (rolls: 2, merged here);
      - a group rolls at group_rate, then picks one of its items by weight: an item's share is its rate over the sum
        of the group's rates (they needn't add to 1000);
      - every row rolls on a kill, steal and despoil ones too (most have rate 0: stolen only).
    `chance` is the base chance per kill, 0 to 1: before Treasure Hunter and the server's DROP_RATE_MULTIPLIER.
]]--

local drops = {}

local KINDS = { [0] = 'drop', [1] = 'group', [2] = 'steal', [4] = 'despoil' }

function drops.source()
    local ok, t = pcall(require, 'data.drops')
    return ok and type(t) == 'table' and t or {}
end

local parsed = {}

-- Drop list `id`'s drops, in the server's order; empty for none.
function drops.of(id)
    id = tonumber(id)
    if not id or id == 0 then return {} end
    if parsed[id] then return parsed[id] end
    local out, seen, totals = {}, {}, {}
    for t, g, gr, item, rate in tostring(drops.source()[id] or ''):gmatch('(%d+),(%d+),(%d+),(%d+),(%d+)') do
        local d = { kind = KINDS[tonumber(t)] or 'drop', group = tonumber(g), group_rate = tonumber(gr),
                    item = tonumber(item), rate = tonumber(rate), rolls = 1 }
        local key = table.concat({ d.kind, d.group, d.item, d.kind == 'group' and '' or d.rate }, ',')
        local same = seen[key]
        if same and d.kind == 'group' then
            same.rate = same.rate + d.rate  -- one item twice in a group: its weights add
        elseif same then
            same.rolls = same.rolls + 1     -- twice on its own: two rolls
        else
            seen[key] = d
            out[#out + 1] = d
        end
        if d.kind == 'group' then totals[d.group] = (totals[d.group] or 0) + d.rate end
    end
    for _, d in ipairs(out) do
        local p = d.rate / 1000
        if d.kind == 'group' then
            d.share = totals[d.group] > 0 and d.rate / totals[d.group] or 0
            d.chance = d.group_rate / 1000 * d.share
        else
            d.chance = 1 - (1 - math.min(p, 1)) ^ d.rolls
        end
    end
    parsed[id] = out
    return out
end

function drops.reset() parsed = {} end

-- A rate per 1000 as a percentage: '15%', '0.5%', '100%'.
local function pct(r) return (('%.1f'):format((r or 0) / 10):gsub('%.0$', '')) .. '%' end
drops.pct = pct

-- A chance 0 to 1 as a percentage, as pct.
local function pc(x) return pct(x * 1000) end

-- How drop `d` comes, its base chance per kill first: '15%', '27.8% (2 rolls of 15%)', '12% (group 1: 50%, then
-- 24% of its picks)', 'steal', 'steal; 10% on a kill'.
function drops.chance(d)
    if d.kind == 'steal' or d.kind == 'despoil' then
        return d.rate > 0 and ('%s; %s on a kill'):format(d.kind, pct(d.rate)) or d.kind
    end
    if d.kind == 'group' then
        return ('%s (group %d: %s, then %s of its picks)'):format(pc(d.chance), d.group, pct(d.group_rate), pc(d.share))
    end
    if (d.rolls or 1) > 1 then return ('%s (%d rolls of %s)'):format(pc(d.chance), d.rolls, pct(d.rate)) end
    return pct(d.rate)
end

return drops
