--[[
    The Zone Browser's lists: every mob and NPC of a zone, from the server's own sql (data/spawns.lua, generated by
    tools/gen_data.lua), each zone parsed the first time it's shown. Pure.

    An entry is a mob group (the mobs of one name and group) or an NPC name:
      { key, kind = 'mob' | 'npc', name, low (lowered, for the filter), zone, ids = { server id, ... } }
    and for a mob: lo, hi (its levels), type (mob type flags), respawn (seconds), spawn (spawn type flags), family,
    job, nm, drop (its drop list: core/drops.lua); for an NPC: status (0 shown, 2 hidden, 6 cutscene only).

    A server id is 0x1000000 + zone * 4096 + its index in the zone. In another zone than yours the server finds a mob
    only while that zone runs on your map process: one-process dev servers find them all.
]]--

local spawns = {}

local BASE = 0x1000000

function spawns.id(zone, index) return BASE + zone * 4096 + index end
function spawns.zone_of(id) return math.floor((id - BASE) / 4096) end

-- Mob types (mobentity.h's MOBTYPE_*), as tags.
local NM, FISHED, CALLED, BATTLEFIELD, EVENT = 0x02, 0x04, 0x08, 0x10, 0x20
local TYPE_TAGS = { { NM, 'NM' }, { FISHED, 'Fished' }, { CALLED, 'Called' }, { BATTLEFIELD, 'Battlefield' }, { EVENT, 'Event' } }

-- Spawn types (SPAWNTYPE_*): when it spawns.
local SPAWN_TYPES = {
    { 0x01, 'at night (20:00 to 4:00)' }, { 0x02, 'in the evening (18:00 to 6:00)' }, { 0x04, 'in its weather' },
    { 0x08, 'in fog (2:00 to 7:00)' }, { 0x10, 'by moon phase' }, { 0x20, 'by lottery (its placeholder)' },
    { 0x40, 'in a time window' }, { 0x80, 'by script (popped, or an event)' },
}

local NPC_STATUS = { [2] = 'hidden', [3] = 'invisible', [6] = 'cutscene only' }

local function source()
    local ok, t = pcall(require, 'data.spawns')
    return ok and type(t) == 'table' and t or { zones = {}, families = {} }
end
spawns.source = source  -- the tests swap it

-- The ids of ranges '1-3,7' in `zone`.
local function expand(zone, s)
    local ids = {}
    for part in s:gmatch('[^,]+') do
        local a, b = part:match('^(%d+)%-(%d+)$')
        a, b = tonumber(a or part), tonumber(b or part)
        if a and b then
            for i = a, b do ids[#ids + 1] = spawns.id(zone, i) end
        end
    end
    return ids
end

local function split(line)
    local f = {}
    for v in (line .. '|'):gmatch('([^|]*)|') do f[#f + 1] = v end
    return f
end

local parsed = {}

-- Zone `zone`'s entries, in id order (parsed once). Empty for a zone with none.
function spawns.zone(zone)
    zone = tonumber(zone)
    if not zone then return {} end
    if parsed[zone] then return parsed[zone] end
    local src = spawns.source()
    local s = src.zones and src.zones[zone]
    local out = {}
    for line in tostring(s or ''):gmatch('[^\n]+') do
        local f = split(line)
        local e
        if f[1] == 'm' and #f >= 10 then
            local t = tonumber(f[5]) or 0
            e = { kind = 'mob', name = f[2], lo = tonumber(f[3]) or 0, hi = tonumber(f[4]) or 0, type = t,
                  respawn = tonumber(f[6]) or 0, spawn = tonumber(f[7]) or 0, family = tonumber(f[8]) or 0,
                  job = tonumber(f[9]) or 0, nm = bit.band(t, NM) ~= 0, drop = #f >= 11 and tonumber(f[10]) or 0,
                  ids = expand(zone, f[#f]) }
        elseif f[1] == 'n' and #f >= 4 then
            e = { kind = 'npc', name = f[2], status = tonumber(f[3]) or 0, ids = expand(zone, f[4]) }
        end
        if e and #e.ids > 0 then
            e.zone, e.low, e.key = zone, e.name:lower(), zone .. ':' .. #out + 1
            out[#out + 1] = e
        end
    end
    parsed[zone] = out
    return out
end

local by_id = {}  -- [zone] = { mob = { [server id] = entry }, npc = { ... } }

-- The entry holding server id `id` (in its zone), or nil: of kind `kind` ('mob' or 'npc') when given, as a few ids
-- are both (a chest that's a mob and an NPC); else the mob. (Maps made once per zone: the Target page asks each
-- frame.)
function spawns.find(id, kind)
    id = tonumber(id)
    if not id or id < BASE then return nil end
    local zone = spawns.zone_of(id)
    local maps = by_id[zone]
    if not maps then
        maps = { mob = {}, npc = {} }
        for _, e in ipairs(spawns.zone(zone)) do
            for _, x in ipairs(e.ids) do maps[e.kind][x] = maps[e.kind][x] or e end
        end
        by_id[zone] = maps
    end
    if kind == 'mob' or kind == 'npc' then return maps[kind][id] end
    return maps.mob[id] or maps.npc[id]
end

-- Every zone, for a search of them all: parsed a few a frame (spawns.step), so a search never stalls the game.
local every = { zones = nil, next = 1 }

-- Parses up to `budget` more zones for spawns.search. Returns whether every zone is: done, and how many are.
function spawns.step(budget)
    if not every.zones then
        every.zones = {}
        for z in pairs(spawns.source().zones or {}) do every.zones[#every.zones + 1] = z end
        table.sort(every.zones)
    end
    local stop = math.min(#every.zones, every.next + (budget or 30) - 1)
    for k = every.next, stop do spawns.zone(every.zones[k]) end
    every.next = stop + 1
    return every.next > #every.zones, every.next - 1, #every.zones
end

-- The entries of every zone parsed so far that spawns.filter keeps, by zone then id, at most `limit` (200);
-- and whether there were more.
function spawns.search(kind, q, limit)
    limit = limit or 200
    local out = {}
    for k = 1, every.next - 1 do
        for _, e in ipairs(spawns.filter(spawns.zone(every.zones[k]), kind, q)) do
            if #out >= limit then return out, true end
            out[#out + 1] = e
        end
    end
    return out, false
end

-- Forget what was parsed (the tests' new source).
function spawns.reset() parsed, by_id, every = {}, {}, { zones = nil, next = 1 } end

-- How many mobs, NMs and NPCs `list` holds: counted by id, not by row.
function spawns.counts(list)
    local c = { mob = 0, nm = 0, npc = 0 }
    for _, e in ipairs(list) do
        if e.kind == 'npc' then c.npc = c.npc + #e.ids
        else
            c.mob = c.mob + #e.ids
            if e.nm then c.nm = c.nm + #e.ids end
        end
    end
    return c
end

-- The entries of `list` of kind `kind` ('all', 'nm', 'mob' for every mob, 'npc') whose name holds every word of
-- `q` (any case). A number alone finds the entry with that server id, or that index in the zone.
function spawns.filter(list, kind, q)
    q = tostring(q or ''):lower()
    local want = {}
    for w in q:gmatch('%S+') do want[#want + 1] = w end
    local n = #want == 1 and want[1]:match('^%d+$') and tonumber(want[1]) or nil
    local out = {}
    for _, e in ipairs(list) do
        local fits = kind == 'all' or (kind == 'nm' and e.nm) or (kind == 'mob' and e.kind == 'mob') or (kind == 'npc' and e.kind == 'npc')
        if fits then
            local hit = true
            if n then
                hit = false
                for _, id in ipairs(e.ids) do
                    if id == n or id - spawns.id(e.zone, 0) == n then hit = true break end
                end
                if not hit then  -- a number in a name (Goblin_Slaughterman No.2)
                    hit = e.low:find(want[1], 1, true) ~= nil
                end
            else
                for _, w in ipairs(want) do if not e.low:find(w, 1, true) then hit = false break end end
            end
            if hit then out[#out + 1] = e end
        end
    end
    return out
end

-- '1h 30m', '16m', '45s'; '' for none.
function spawns.duration(s)
    s = math.floor(tonumber(s) or 0)
    if s <= 0 then return '' end
    local d, h, m = math.floor(s / 86400), math.floor(s % 86400 / 3600), math.floor(s % 3600 / 60)
    local out = {}
    if d > 0 then out[#out + 1] = d .. 'd' end
    if h > 0 then out[#out + 1] = h .. 'h' end
    if m > 0 then out[#out + 1] = m .. 'm' end
    if #out == 0 then out[1] = s .. 's' end
    return table.concat(out, ' ')
end

-- An entry's tags: { 'NM', 'Lottery' }, { 'hidden' }...
function spawns.tags(e)
    local out = {}
    if e.kind == 'mob' then
        for _, t in ipairs(TYPE_TAGS) do if bit.band(e.type or 0, t[1]) ~= 0 then out[#out + 1] = t[2] end end
        -- (not 'scripted': most mobs are, 0x80; the description says so)
        if bit.band(e.spawn or 0, 0x20) ~= 0 then out[#out + 1] = 'Lottery' end
    elseif NPC_STATUS[e.status] then
        out[1] = NPC_STATUS[e.status]
    end
    return out
end

-- 'Lv 10-12', 'Lv 75', or '' (no levels in its group).
function spawns.levels(e)
    if e.kind ~= 'mob' or (e.lo or 0) == 0 and (e.hi or 0) == 0 then return '' end
    if e.lo == e.hi or e.hi == 0 then return 'Lv ' .. e.lo end
    return ('Lv %d-%d'):format(e.lo, e.hi)
end

-- What entry `e` is, in lines, for a tooltip. `jobs`: { [id] = 'WAR' }.
function spawns.describe(e, jobs)
    local src = spawns.source()
    local out = { e.name .. (#spawns.tags(e) > 0 and (' (' .. table.concat(spawns.tags(e), ', ') .. ')') or '') }
    if e.kind == 'mob' then
        local bits = {}
        if spawns.levels(e) ~= '' then bits[#bits + 1] = spawns.levels(e) end
        if jobs and jobs[e.job] then bits[#bits + 1] = jobs[e.job] end
        local fam = src.families and src.families[e.family]
        if fam then bits[#bits + 1] = fam .. ' family' end
        if #bits > 0 then out[#out + 1] = table.concat(bits, ', ') end
        local when = {}
        if e.respawn > 0 then when[#when + 1] = 'respawns in ' .. spawns.duration(e.respawn) end
        for _, t in ipairs(SPAWN_TYPES) do
            if bit.band(e.spawn or 0, t[1]) ~= 0 then when[#when + 1] = 'spawns ' .. t[2] end
        end
        if #when > 0 then out[#out + 1] = table.concat(when, '; ') end
    end
    local shown = {}
    for k = 1, math.min(#e.ids, 6) do shown[k] = tostring(e.ids[k]) end
    out[#out + 1] = (#e.ids == 1 and 'Id ' or 'Ids ') .. table.concat(shown, ', ') .. (#e.ids > 6 and (' and ' .. (#e.ids - 6) .. ' more') or '')
    return out
end

-- A mob a script owns: a battlefield's, an event's, or one called by another (a pet, an add). Spawned by hand, it
-- can leave that script's state wrong: its Spawn asks twice.
local SCRIPTED = BATTLEFIELD + EVENT + CALLED
function spawns.owned(e) return e.kind == 'mob' and bit.band(e.type or 0, SCRIPTED) ~= 0 end

-- What a row offers for id `id` of entry `e`: { label, line, tip, asks twice }. `here`: it's in your zone (bring
-- works only there: the server despawns a mob it can't move).
function spawns.buttons(e, id, here)
    local out = {}
    if e.kind == 'mob' then
        local owned = spawns.owned(e)
        out[#out + 1] = { 'Spawn', '!spawnmob ' .. id, owned
            and 'Spawn it at its spawn point. A battlefield\'s, event\'s or called mob: its script may not expect it'
            or 'Spawn it at its spawn point (if it isn\'t up)', owned }
        out[#out + 1] = { 'Go to', '!gotoid ' .. id, here and 'Go to it (where it is, else where it was last)'
            or 'Go to it: zones you there' }
        if here then out[#out + 1] = { 'Bring', '!mobhere ' .. id, 'Spawn it if needed and move it to you', true } end
        out[#out + 1] = { 'Despawn', '!despawnmob ' .. id, 'Despawn it', true }
    else
        out[#out + 1] = { 'Go to', '!gotoid ' .. id, here and 'Go to it' or 'Go to it: zones you there' }
        if here then out[#out + 1] = { 'Bring', '!npchere ' .. id, 'Move it to you and show it, hidden or not, for everyone in the zone', true } end
    end
    return out
end

return spawns
